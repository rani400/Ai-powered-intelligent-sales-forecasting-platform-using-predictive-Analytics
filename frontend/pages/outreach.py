"""Outreach page - generate, preview and store personalised first-touch email drafts."""

from __future__ import annotations

import os
import sys

import pandas as pd
import streamlit as st

FRONTEND_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if FRONTEND_DIR not in sys.path:
    sys.path.insert(0, FRONTEND_DIR)

from api_client import ApiError, SalesGenieApi  # noqa: E402

st.set_page_config(
    page_title="Outreach - SalesGenie AI", page_icon="SG", layout="wide"
)

api = SalesGenieApi(st.session_state.get("api_base_url"))

st.title("AI Outreach")
st.write(
    "Generate a personalised first-touch email for a prospect. Every draft is stored with "
    "status 'draft' - nothing is sent automatically, because no sending workflow exists yet."
)

if not api.is_reachable():
    st.error(
        "The backend is not reachable. Start it with "
        "`python -m uvicorn app.main:app --app-dir backend`."
    )
    st.stop()

try:
    listing = api.list_leads(limit=200)
except Exception as exc:  # noqa: BLE001
    st.error(f"Could not load leads: {exc}")
    st.stop()

items = listing.get("items", [])
if not items:
    st.info("No leads recorded yet. Import a CSV on the Leads page first.")
    st.stop()

lead_ids = [item["lead_id"] for item in items]
selected_id = st.selectbox(
    "Select a prospect",
    lead_ids,
    format_func=lambda value: (
        f"#{value} - "
        + next(
            (
                f"{i['company_name']} ({i.get('contact_name') or 'no contact'})"
                for i in items
                if i["lead_id"] == value
            ),
            "unknown",
        )
    ),
)
selected = next(item for item in items if item["lead_id"] == selected_id)

st.subheader("Draft options")
col1, col2, col3 = st.columns(3)
tone = col1.selectbox("Tone", ["professional", "friendly"])
email_length = col2.selectbox("Length", ["short", "detailed"])
goal = col3.selectbox(
    "Goal",
    ["product_introduction", "meeting", "follow_up"],
    format_func=lambda value: value.replace("_", " ").title(),
)
product = st.text_input(
    "Product or service being offered *",
    value="SalesGenie AI lead intelligence platform",
)

if st.button("Generate draft", type="primary"):
    payload = {
        "lead_id": selected_id,
        "product_or_service": product.strip(),
        "communication_goal": goal,
        "tone": tone,
        "email_length": email_length,
    }
    try:
        draft = api.generate_outreach(payload)
        st.session_state.outreach_draft = draft
        st.success(f"Draft {draft['campaign_id']} generated and stored.")
    except Exception as exc:  # noqa: BLE001
        st.error(f"Could not generate the draft: {exc}")
        st.session_state.pop("outreach_draft", None)

draft = st.session_state.get("outreach_draft")
if draft:
    st.divider()
    st.subheader("Latest draft")
    if draft.get("is_mock"):
        st.warning(
            "This draft was produced by the offline mock generator, not by an AI model, "
            "because no LLM provider key is configured. Configure LLM_API_KEY in `.env` "
            "to enable real generation."
        )
    else:
        st.caption(f"Generated by provider: {draft.get('provider')}")

    st.markdown("**Subject**")
    st.write(draft.get("email_subject", ""))
    st.markdown("**Body**")
    st.text_area(
        "Email body",
        value=draft.get("email_content", ""),
        height=320,
        key="outreach_body_preview",
        disabled=True,
    )
    st.caption(
        f"Status: {draft.get('campaign_status')} · Tone: {draft.get('tone')} · "
        f"Length: {draft.get('email_length')} · Goal: {draft.get('communication_goal')}"
    )

st.divider()
st.subheader("Stored drafts")
try:
    drafts = api.list_outreach()
except Exception as exc:  # noqa: BLE001
    st.error(f"Could not load stored drafts: {exc}")
    drafts = {"items": [], "total": 0}

if drafts.get("items"):
    frame = pd.DataFrame(drafts["items"])[
        ["campaign_id", "lead_id", "email_subject", "campaign_status", "tone", "is_mock"]
    ]
    st.dataframe(frame, width="stretch", hide_index=True)
else:
    st.info("No drafts have been generated yet.")
